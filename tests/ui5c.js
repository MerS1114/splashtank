const {PAGE, OUT} = require('./paths');
const chromium=require('@sparticuz/chromium').default; const puppeteer=require('puppeteer-core');
const wait=(ms)=>new Promise(r=>setTimeout(r,ms));
(async()=>{ const exe=await chromium.executablePath();
 const br=await puppeteer.launch({executablePath:exe,args:[...chromium.args,'--enable-unsafe-webgpu','--enable-features=Vulkan,WebGPU','--use-webgpu-adapter=swiftshader','--use-angle=swiftshader','--ignore-gpu-blocklist','--allow-file-access-from-files'],headless:'shell'});
 const pg=await br.newPage(); await pg.setViewport({width:1440,height:900}); const errs=[]; pg.on('console',m=>{const t=m.text(); if(/rror|nvalid/.test(t)) errs.push(t.slice(0,300));}); pg.on('pageerror',e=>errs.push('PAGE '+e.message));
 await pg.goto('file://'+PAGE); await wait(6000);
 const ev=(f,...a)=>pg.evaluate(f,...a);
 await pg.select('#scene','Dam break'); await wait(3000);
 const st=()=>ev(()=>{ const s=window.__splash, sim=s.getSim(), fr=sim.outFrame; let deep=0; if(fr&&fr.dp) for(let i=0;i<fr.dp.n;i++) if(fr.dp.spd[i]!==255) deep++; return {N:sim.N, nbOn:sim.nbOn, deepOn:!!sim.deepOn, deep, shown:fr?fr.n:0, spray:fr&&fr.sp?fr.sp.n:0, S_nb:s.S.nbOn}; });
 console.log('start', JSON.stringify(await st()));
 await pg.click('#ptabs [data-ptab=sim]'); await wait(200);
 await ev(()=>{ const c=document.querySelector('#c-nb'); c.closest('details').open=true; c.scrollIntoView({block:'center'}); }); await wait(200);
 await pg.click('#c-nb'); await wait(1500);
 await pg.click('#btn-play'); await wait(4000); await pg.click('#btn-play'); await wait(500);
 console.log('nb on', JSON.stringify(await st()));
 await ev(()=>document.querySelector('#c-nblook').scrollIntoView({block:'center'})); await pg.click('#c-nblook'); await wait(300);
 await pg.click('#btn-play'); await wait(3000); await pg.click('#btn-play'); await wait(800);
 console.log('nb look', JSON.stringify(await st()));
 await ev(()=>{ window.__splash.snapView('front'); }); await wait(1200);
 await pg.screenshot({path:OUT+'/u5_nblook.png'});
 await pg.select('#vh-colby','type'); await wait(500);
 console.log('colour by type', JSON.stringify(await ev(()=>({mode:window.__splash.S.colorBy, legend:!document.querySelector('#legend').hidden, sel:document.querySelector('#d-colby') && document.querySelector('#d-colby').value}))));
 await pg.screenshot({path:OUT+'/u5_type.png'});
 await ev(()=>document.querySelector('#c-nb').scrollIntoView({block:'center'})); await pg.click('#c-nb'); await wait(1500);
 await pg.click('#btn-play'); await wait(3000); await pg.click('#btn-play'); await wait(500);
 console.log('nb off again', JSON.stringify(await st()));
 await pg.screenshot({path:OUT+'/u5_nboff.png'});
 console.log('errs', JSON.stringify(errs.slice(0,10)));
 await br.close();
})().catch(e=>console.log('ERR',e.stack));
