// Writes the page's Simulation settings (the rows buildLiveUI in src/app/05-panels.js makes for FLIP: label, range, step, default, tooltip)
// for the native window's panels, so the two show the same settings with the same words. Run after changing those rows:
//   node native/tools/export-settings.js          writes native/app/src/settings.json
//   node native/tools/export-settings.js --check  exits 1 when that file is out of date (the native tests run this)
// Each row says where its value lives in a scene file (sceneData in src/app/13-files.js): solver.<key>, solver.wind.<key> or ocean.<key>.
const fs = require('fs'), path = require('path'), vm = require('vm');
const root = path.join(__dirname, '../..'), outFile = path.join(__dirname, '../app/src/settings.json');
const panels = fs.readFileSync(path.join(root, 'src/app/05-panels.js'), 'utf8');
const state = fs.readFileSync(path.join(root, 'src/app/00-state.js'), 'utf8');

// the page's defaults: S, OCEAN_DEF and the FLIP preset (iterations)
const lit = (name) => { const i = state.indexOf('const ' + name + ' = {'); let d = 0, j = state.indexOf('{', i); const s = j; for (; j < state.length; j++) { if (state[j] === '{') d++; else if (state[j] === '}' && --d === 0) break; } return state.slice(s, j + 1); };
const S0 = vm.runInNewContext('(' + lit('S') + ')'), OC = vm.runInNewContext('(' + lit('OCEAN_DEF') + ')'), PRE = vm.runInNewContext('(' + lit('PRESET') + ')');
S0.iters = PRE.flip.iters;

// the keys a scene file saves (sceneData), so only settings that travel with the scene are shown
const files = fs.readFileSync(path.join(root, 'src/app/13-files.js'), 'utf8');
const saved = new Set([...files.match(/solver: \{([^}]*)\}/)[1].matchAll(/(\w+): S\.\w+/g)].map((m) => m[1]));
// the Speed-ups switches are not in the page's scene files; the native program keeps them under solver (the page ignores them there)
const NATIVE_EXTRA = ['sortP', 'ballistic', 'settle', 'mg', 'p2gWin'];
for (const k of NATIVE_EXTRA) saved.add(k);

const NB_FULL = Number(state.match(/const NB_FULL = (\d+)/)[1]);
const body = panels.slice(panels.indexOf('function buildLiveUI'), panels.indexOf('const gd = $(\'#g-disp\')'));
const str = (s) => s.replace(/\\'/g, '\'').replace(/×/g, 'x').replace(/·/g, '-');
const q = (re, line) => { const m = line.match(re); return m ? m[1] : undefined; };
const groups = { gs: null };   // variable -> group index
const out = { note: 'Generated by native/tools/export-settings.js from src/app/05-panels.js. Do not edit; change the page and run the script again.', groups: [], rows: [] };
const num = (v) => (v === undefined ? undefined : v === 'NB_FULL' ? NB_FULL : Number(v));
for (const raw of body.split('\n')) {
  const line = raw.trim();
  let m = line.match(/const (\w+) = sub\((\w+), '([\w-]+)', '([^']*)', ([^,]+?)(?:, '((?:\\'|[^'])*)')?\);/);
  if (m) {
    const [, v, parent, id, title, open, tip] = m;
    groups[v] = out.groups.length;
    out.groups.push({ id, title: str(title), parent: groups[parent] ?? null, open: open === 'true', tip: tip ? str(tip) : '' });
    continue;
  }
  const g = groups[q(/^(?:if \(\w+\) |const \w+ = )?add(?:Slider|Check)\((\w+),/, line)] ?? groups.op;
  const tip = str(q(/tip: '((?:\\'|[^'])*)'/, line) || '');
  if (/^(?:if \(\w+\) )?addSlider\(/.test(line)) {
    const vm1 = line.match(/value: (1 \/ )?S\.([\w.]+)/);
    if (!vm1 || !/^-?[\d.]+$/.test(q(/min: ([^,]+),/, line) || '')) continue;   // rows sized by the solver preset (spacing, Max points) are the Bake panel's
    const key = vm1[2], inv = !!vm1[1];
    const unit = q(/fmt: \(v\) => [^,]*?\+ '([^']+)'/, line) || '';
    out.rows.push({ group: g, kind: 'slider', label: str(q(/label: '((?:\\'|[^'])*)'/, line)), key, inv, min: num(q(/min: ([^,]+),/, line)), max: num(q(/max: ([^,]+),/, line)),
      step: num(q(/step: ([\d.]+)/, line)), log: /log: true/.test(line), round: num(q(/round: ([\d.]+)/, line)), unit: str(unit.trim()), off: /v === 0 \? 'off'/.test(line), tip });
  } else if (/^(?:if \(\w+\) |const \w+ = )?addCheck\(/.test(line)) {
    const c = line.match(/addCheck\(\w+, '[\w-]+', '([^']*)', S\.([\w.]+)(?: \|\| S\.[\w.]+)?, '((?:\\'|[^'])*)'/);
    if (c) out.rows.push({ group: g, kind: 'check', label: str(c[1]), key: c[2], tip: str(c[3]) });
  } else if (/^ocS\(/.test(line)) {
    const o = line.match(/ocS\('[\w-]+', '([^']*)', '(\w+)', ([\d.-]+), ([\d.-]+), \{(.*)\}\);/);
    if (!o) continue;
    const rest = o[5];
    out.rows.push({ group: groups.op, kind: 'slider', label: str(o[1]), key: 'ocean.' + o[2], inv: false, min: +o[3], max: +o[4], step: num(q(/step: ([\d.]+)/, rest)), log: /log: true/.test(rest),
      round: num(q(/round: ([\d.]+)/, rest)), unit: str((q(/fmt: \(v\) => [^,]*?\+ '([^']+)'/, rest) || '').trim()), pct: /\* 100\)/.test(rest), off: false, tip: str(q(/tip: '((?:\\'|[^'])*)'/, rest) || '') });
  }
}
// where each value lives in the scene file, and its default; rows whose setting is not saved in scene files are left out
const where = (k) => k.startsWith('ocean.') ? ['ocean', k.slice(6)] : k.startsWith('wind.') ? ['solver', 'wind', k.slice(5)] : ['solver', k];
const defOf = (k) => k.startsWith('ocean.') ? OC[k.slice(6)] : k.split('.').reduce((o, p) => (o == null ? undefined : o[p]), S0);
// left out: the PBF solvers' rows (Viscosity, Iterations), Max points (the Bake panel's) and Drag speed (dragging objects while the live sim runs)
const skip = new Set(['visc', 'cap', 'dragSpeed']);
out.rows = out.rows.filter((r) => !skip.has(r.key) && r.label !== 'Iterations').filter((r) => r.key.startsWith('ocean.') || saved.has(r.key.split('.')[0])).map((r) => Object.assign(r, { path: where(r.key), def: defOf(r.key) }));
// the Enabled box of the narrow band is S.nbOn || S.ocean.on: it is nbOn
for (const r of out.rows) if (r.key === 'nbOn') r.label = 'Enabled';
// native only: tall cells (native/sim/shaders/tall.wgsl), in Speed-ups
{
  const su = out.groups.findIndex((g) => g.id === 'speedups');
  out.rows.push({ group: su, kind: 'check', label: 'Tall cells (native)', key: 'tallCells', path: ['solver', 'tallCells'], def: true,
    tip: 'Native program only, narrow band only: deep water well under the band is kept as one tall cell per column instead of a cell every spacing, so deep lakes and oceans need a fraction of the grid (a deep ocean baked about 3 times faster). When the surface, particles, an object or a source comes near, that depth goes back to ordinary cells. Objects and sources low in the water keep ordinary cells near them from the start. The web page ignores this setting.' });
}
// native only: the sharp water surface (ghost fluid from the particles' surface field), in Physics
{
  const ph = out.groups.findIndex((g) => g.id === 'phys');
  out.rows.push({ group: ph, kind: 'check', label: 'Sharp water surface', key: 'ghost', path: ['solver', 'ghost'], def: true,
    tip: 'The pressure meets the air where the water\'s surface really is inside each cell, worked out from the particles every step, instead of at the middle of the next cell. Waves keep their height and timing (a standing wave lost 13% of its height a period without it, 2.7% with it) and splashes rise more freely. Costs about a tenth more time. The web page ignores this setting.' });
}
{
  const ph = out.groups.findIndex((g) => g.id === 'phys');
  out.rows.push({ group: ph, kind: 'check', label: 'Smooth walls', key: 'smoothWalls', path: ['solver', 'smoothWalls'], def: true,
    tip: 'Objects cut through grid cells smoothly, so slopes and curves stay slopes and curves to the water, instead of stairs that catch it. The web page ignores this setting.' });
}
// native defaults that differ from the page's: the grouped transfer (on: with the finer sort it took particle to grid from 6.8 to 2.2 ms a
// step on Mer's ocean, the same water; the page left it off)
for (const r of out.rows) if (r.key === 'p2gWin') {
  r.def = true;
  r.tip = 'Particles hand their velocity to the grid through a small patch of the grid kept in fast workgroup memory, instead of each particle going to the grid on its own. Exactly the same result, much faster in big scenes. Needs Sort particles on to help.';
}
// whitewater looks (WW_LOOKS: Impact is the defaults)
{
  const keys = vm.runInNewContext(panels.match(/const WW_KEYS = (\[[^\]]*\]);/)[1]);
  const looks = {};
  for (const n of ['calm', 'waves', 'storm']) looks[n] = vm.runInNewContext('(' + panels.match(new RegExp(n + ': (\\{[^}]*\\})'))[1] + ')');
  looks.impact = Object.fromEntries(keys.map((k) => [k, S0[k]]));
  out.looks = { keys, order: [['calm', 'Calm'], ['waves', 'Breaking waves'], ['impact', 'Impact'], ['storm', 'Storm']], values: looks,
    tip: 'Starting points for the whitewater settings. Pick one, then fine-tune; changing any setting by hand makes it Custom.' };
}
const text = JSON.stringify(out, null, 1) + '\n';
if (process.argv.includes('--check')) {
  const lf = (t) => t.split('\r\n').join('\n');
  let cur = ''; try { cur = lf(fs.readFileSync(outFile, 'utf8')); } catch (e) { /* missing */ }
  if (cur !== text) { console.error('Out of date: native/app/src/settings.json. Run node native/tools/export-settings.js'); process.exit(1); }
  console.log('settings up to date');
} else {
  fs.writeFileSync(outFile, text);
  console.log('wrote settings.json: ' + out.groups.length + ' groups, ' + out.rows.length + ' rows');
}
