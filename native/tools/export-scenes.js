// Writes the page's starting scenes (the Scene list: the ones built in code in src/app/04-scenes.js and the presets in src/presets.js)
// as scene files for the native window's New scene, by opening each in the built page and saving it the way Save scene does
// (sceneData), so both programs start from the same scenes. Run after changing those scenes (needs npm run build first):
//   node native/tools/export-scenes.js        writes native/app/src/scenes.json
const fs = require('fs'), path = require('path');
const { open, wait, done } = require('../../tests/lib');
(async () => {
  const t = await open(null);
  const names = await t.ev(() => [...document.querySelectorAll('#scene option')].map((o) => o.value));
  const out = {};
  for (const n of names) {
    await t.pg.select('#scene', n);
    await wait(2500);
    const d = await t.ev(() => window.__splash.sceneData());
    delete d.saved;   // the time it was saved: would change the file on every run
    out[n] = d;
    console.log(n + ': ' + d.objs.length + ' objects, ' + (d.fills || []).length + ' fills');
  }
  if (t.errs.length) console.log('page errors: ' + t.errs.join(' | '));
  fs.writeFileSync(path.join(__dirname, '../app/src/scenes.json'), JSON.stringify({ note: 'Generated by native/tools/export-scenes.js from the page. Do not edit; change the page\'s scenes and run the script again.', order: names, scenes: out }) + '\n');
  console.log('wrote scenes.json');
  await done(t);
})();
