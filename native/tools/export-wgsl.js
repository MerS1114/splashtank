// Writes the page's FLIP shader (flipWGSL() in src/flip/sim.js, from the src/flip/wgsl-*.js parts) and its binding table (FLIP_L) for
// the native solver, so the shaders are written in one place only. Run after changing any of them:
//   node native/tools/export-wgsl.js          writes native/sim/shaders/
//   node native/tools/export-wgsl.js --check  exits 1 when the files there are out of date (the native tests run this)
const fs = require('fs'), path = require('path'), vm = require('vm');
const root = path.join(__dirname, '../..'), out = path.join(__dirname, '../sim/shaders');
const files = ['src/shared.js', 'src/gpu.js', 'src/flip/wgsl-core.js', 'src/flip/wgsl-blocks.js', 'src/flip/wgsl-solver.js', 'src/flip/wgsl-whitewater.js', 'src/flip/wgsl-narrowband.js',
  'src/flip/wgsl-multigrid.js', 'src/flip/wgsl-subgroups.js', 'src/flip/sim.js'];
const noop = () => {};
const ctx = vm.createContext({ console, Math, performance: { now: () => 0 }, WeakMap, Map, Set, Promise, Float32Array, Uint32Array, Uint16Array, Uint8Array, Int32Array, ArrayBuffer, DataView,
  navigator: {}, GPUBufferUsage: {}, GPUMapMode: {}, setTimeout: noop, self: {} });
const src = files.map((f) => fs.readFileSync(path.join(root, f), 'utf8')).join('\n;\n');
vm.runInContext(src + '\n;this.__out = { plain: flipWGSL(false), sg: flipWGSL(true), L: FLIP_L, params: FLIP_PARAMS_BYTES, mgLevels: FLIP_MG_LEVELS, deepMax: FLIP_DEEPMAX };', ctx, { filename: 'flip-export' });
const o = ctx.__out;
const head = '// Generated by native/tools/export-wgsl.js from src/flip/*.js. Do not edit; change the page\'s shader and run the script again.\n';
const want = {
  'flip.wgsl': head + o.plain,
  'flip_sg.wgsl': head.replace('// ', '') .startsWith('Generated') ? o.sg.replace('enable subgroups;\n', 'enable subgroups;\n' + head) : o.sg,
  'flip_layout.json': JSON.stringify({ note: head.slice(3).trim(), paramsBytes: o.params, mgLevels: o.mgLevels, deepMax: o.deepMax, bindings: o.L }, null, 1) + '\n',
};
if (process.argv.includes('--check')) {
  // line endings do not count: git on Windows may check the files out with CRLF
  const lf = (t) => t.split('\r\n').join('\n');
  const stale = Object.keys(want).filter((f) => { try { return lf(fs.readFileSync(path.join(out, f), 'utf8')) !== lf(want[f]); } catch (e) { return true; } });
  if (stale.length) { console.error('Out of date: ' + stale.join(', ') + '. Run node native/tools/export-wgsl.js'); process.exit(1); }
  console.log('shaders up to date');
} else {
  fs.mkdirSync(out, { recursive: true });
  for (const f in want) fs.writeFileSync(path.join(out, f), want[f]);
  console.log('wrote ' + Object.keys(want).join(', ') + ' (' + Object.keys(o.L).length + ' kernels)');
}
